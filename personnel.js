(() => {
  const modal = document.getElementById('personnel-modal');
  if (!modal) return;
  const el = id => document.getElementById(id);
  const fillTags = (id, items, cls = '') => {
    const target = el(id); target.replaceChildren();
    if (!items.length) { const e=document.createElement('p'); e.textContent='No decorations recorded in this profile yet.'; target.append(e); return; }
    items.forEach(item => { const span=document.createElement('span'); span.className='personnel-tag '+cls; span.textContent=item; target.append(span); });
  };
  function show(key) {
    const p=UKJSFG_PERSONNEL[key]; if(!p) return;
    el('personnel-title').textContent=p.title;
    el('personnel-subtitle').textContent=p.position;
    const photo=el('personnel-photo'); photo.src='assets/'+p.photo; photo.alt=p.title+' portrait';
    el('personnel-info').replaceChildren();
    for(const [label,value] of [['RANK',p.rank],['UNIT',p.unit],['POSITION',p.position],['STATUS','Active']]) {
      const item=document.createElement('div');const small=document.createElement('small');small.textContent=label;const strong=document.createElement('strong');strong.textContent=value;item.append(small,strong);el('personnel-info').append(item);
    }
    el('personnel-bio').replaceChildren();
    p.bio.forEach(part => {const para=document.createElement('p');para.textContent=part;el('personnel-bio').append(para);});
    fillTags('personnel-roles',p.roles);fillTags('personnel-qualifications',p.quals);fillTags('personnel-aviation',p.aviation);fillTags('personnel-awards',p.awards,'medal');
    el('personnel-aviation-section').hidden=!p.aviation.length;
    modal.querySelector('details').open=false;
    modal.showModal();
  }
  document.querySelectorAll('.personnel-open').forEach(card => {
    card.addEventListener('click',()=>show(card.dataset.personnel));
    card.addEventListener('keydown',e=>{ if(e.key==='Enter'||e.key===' '){e.preventDefault();show(card.dataset.personnel);} });
  });
  modal.querySelector('.personnel-modal-close').addEventListener('click',()=>modal.close());
  modal.addEventListener('click',e=>{if(e.target===modal)modal.close();});
})();
